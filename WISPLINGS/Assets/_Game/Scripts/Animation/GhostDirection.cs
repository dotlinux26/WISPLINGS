namespace GhostSurvival.Animation
{
    /// <summary>
    /// Four directional facing states matching atlas row order:
    /// Row 0: Down
    /// Row 1: Left
    /// Row 2: Right
    /// Row 3: Up
    /// </summary>
    public enum GhostDirection
    {
        Down = 0,
        Left = 1,
        Right = 2,
        Up = 3
    }
}
