namespace GhostSurvival.Animation
{
    /// <summary>
    /// Eight directional facing states matching atlas row order:
    /// Row 0: Down
    /// Row 1: DownLeft
    /// Row 2: Left
    /// Row 3: UpLeft
    /// Row 4: Up
    /// Row 5: UpRight
    /// Row 6: Right
    /// Row 7: DownRight
    /// </summary>
    public enum GhostDirection
    {
        Down = 0,
        DownLeft = 1,
        Left = 2,
        UpLeft = 3,
        Up = 4,
        UpRight = 5,
        Right = 6,
        DownRight = 7
    }
}

